const categories = [
  "Усі",
  "Запис і візит",
  "КТ та МРТ",
  "Контраст і безпека",
  "Результати й оплата",
] as const;

function normalize(value: string) {
  return value.toLocaleLowerCase("uk-UA").replace(/[’'`]/g, "").trim();
}

export function FaqDirectory() {
  const [activeCategory, setActiveCategory] = useState<(typeof categories)[number]>("Усі");
  const [query, setQuery] = useState("");
  const [openItem, setOpenItem] = useState<number | null>(null);

  const filteredItems = useMemo(() => {
    const normalizedQuery = normalize(query);

    return faqItems
      .map((item, index) => ({ ...item, originalIndex: index }))
      .filter((item) => activeCategory === "Усі" || item.category === activeCategory)
      .filter((item) => {
        if (!normalizedQuery) return true;
        return normalize(`${item.question} ${item.answer} ${item.category}`).includes(normalizedQuery);
      });
  }, [activeCategory, query]);

  return (
    <section className="faq-directory" aria-label="Відповіді на часті запитання">
      <div className="faq-tools">
        <label className="faq-search">
          <svg viewBox="0 0 24 24" aria-hidden="true">
            <circle cx="11" cy="11" r="6.5" />
            <path d="m16 16 4 4" />
          </svg>
          <input
            type="search"
            value={query}
            onChange={(event) => setQuery(event.target.value)}
            placeholder="Знайти відповідь"
            aria-label="Пошук серед частих запитань"
          />
          {query ? (
            <button type="button" onClick={() => setQuery("")} aria-label="Очистити пошук">
              ×
            </button>
          ) : null}
        </label>

        <div className="faq-categories" aria-label="Категорії запитань">
          {categories.map((category) => (
            <button
              className={activeCategory === category ? "is-active" : ""}
              type="button"
              key={category}
              onClick={() => {
                setActiveCategory(category);
                setOpenItem(null);
              }}
            >
              {category}
            </button>
          ))}
        </div>
      </div>

      <div className="faq-list">
        {filteredItems.map((item) => {
          const isOpen = openItem === item.originalIndex;
          const itemId = `faq-answer-${item.originalIndex + 1}`;

          return (
            <article className={`faq-item${isOpen ? " is-open" : ""}`} key={item.question}>
              <button
                className="faq-question"
                type="button"
                aria-expanded={isOpen}
                aria-controls={itemId}
                onClick={() => setOpenItem(isOpen ? null : item.originalIndex)}
              >
                <span className="faq-number">
                  {String(item.originalIndex + 1).padStart(2, "0")}
                </span>
                <span className="faq-question-copy">
                  <small>{item.category}</small>
                  <strong>{item.question}</strong>
                </span>
                <span className="faq-toggle" aria-hidden="true" />
              </button>
              <div className="faq-answer" id={itemId} aria-hidden={!isOpen}>
                <div>
                  <p>{item.answer}</p>
                </div>
              </div>
            </article>
          );
        })}
      </div>

      {filteredItems.length === 0 ? (
        <div className="faq-empty">
          <strong>Відповіді за цим запитом не знайдено</strong>
          <p>Спробуйте коротше формулювання або оберіть іншу категорію.</p>
        </div>
      ) : null}
    </section>
  );
}
